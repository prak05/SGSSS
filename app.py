def plot_gantt(schedule: list) -> go.Figure:
    """
    Generates an interactive Plotly horizontal Gantt chart showing activity start & finish times.
    Optimized for maximum readability and full visibility without requiring manual zooming or panning.
    """
    if not schedule:
        return go.Figure()
    
    sorted_schedule = sorted(schedule, key=lambda e: e.activity_id)
    max_time = max(e.finish_time for e in sorted_schedule) if sorted_schedule else 1
    num_activities = len(sorted_schedule)
    
    # Calculate responsive dynamic height
    dynamic_height = max(450, num_activities * 24 + 100)
    
    fig = go.Figure()
    colors_cycle = px.colors.qualitative.Bold
    
    for idx, entry in enumerate(sorted_schedule):
        duration = entry.finish_time - entry.start_time
        act_label = f"Task {entry.activity_id}"
        color = colors_cycle[idx % len(colors_cycle)]
        
        hover_info = (
            f"<b>Activity {entry.activity_id}</b><br>"
            f"Start Time: {entry.start_time}<br>"
            f"Finish Time: {entry.finish_time}<br>"
            f"Duration: {duration} time units"
        )
        
        text_str = f"{entry.start_time}→{entry.finish_time}" if duration > 0 else "0"
        
        fig.add_trace(go.Bar(
            x=[duration],
            y=[act_label],
            base=[entry.start_time],
            orientation='h',
            name=act_label,
            text=text_str,
            textposition='auto',
            hoverinfo='text',
            hovertext=hover_info,
            marker=dict(
                color=color,
                line=dict(color='rgba(0, 0, 0, 0.3)', width=1)
            )
        ))
    
    dtick_val = max(1, math.ceil(max_time / 20))
    
    fig.update_layout(
        title=dict(
            text="📅 Optimized Activity Execution Gantt Timeline",
            font=dict(size=16)
        ),
        barmode='stack',
        showlegend=False,
        height=dynamic_height,
        margin=dict(l=90, r=40, t=50, b=50),
        xaxis=dict(
            title="Time Units (Periods / Days)",
            range=[-0.5, max_time + 1.5],
            dtick=dtick_val,
            showgrid=True,
            gridcolor='#E2E8F0',
            zeroline=True,
            zerolinecolor='#CBD5E1'
        ),
        yaxis=dict(
            title="Activity ID",
            autorange="reversed",  # Task 1 at top, Task N at bottom
            showgrid=True,
            gridcolor='#F1F5F9'
        ),
        plot_bgcolor='white',
        paper_bgcolor='white',
    )
    return fig

def plot_resources(project, schedule: list) -> list[go.Figure]:
    """
    Generates time-phased resource utilization area charts for each renewable resource.
    Overlays a red dashed line representing maximum resource capacity.
    
    Code Explanation for Presentation:
    - Calculates aggregate resource usage at each discrete time step `t`.
    - If usage <= capacity at all `t`, the schedule is 100% resource-feasible.
    """
    max_time = max([e.finish_time for e in schedule]) if schedule else 0
    figs = []
    for r_id, res_obj in project.resources.items():
        cap = res_obj.capacity
        usage = [0] * (max_time + 1)
        for e in schedule:
            req = project.activities[e.activity_id].resource_requirements.get(r_id, 0)
            for t in range(e.start_time, e.finish_time):
                usage[t] += req
        
        fig = go.Figure()
        fig.add_trace(go.Scatter(
            x=list(range(max_time + 1)),
            y=usage,
            mode='lines',
            fill='tozeroy',
            name='Resource Usage',
            line=dict(color='#1f77b4', width=2)
        ))
        fig.add_hline(
            y=cap,
            line_dash="dash",
            line_color="red",
            annotation_text=f"Max Capacity ({cap})",
            annotation_position="top right"
        )
        fig.update_layout(
            title=f"Resource Limit vs Demand Timeline: {r_id}",
            xaxis_title="Time Step (t)",
            yaxis_title="Units Required",
            height=320
        )
        figs.append(fig)
    return figs

def plot_precedence(project) -> go.Figure:
    """
    Generates an interactive Directed Acyclic Graph (DAG) visualizing activity precedence dependencies.
    Uses topological layering along earliest start times so all graphs (from N=10 to N=120) layout cleanly.
    """
    G = nx.DiGraph()
    for act_id, act in project.activities.items():
        G.add_node(act_id)
        for suc in act.successors:
            G.add_edge(act_id, suc)
    
    try:
        topo_order = list(nx.topological_sort(G))
        eft, est = {}, {}
        for a in topo_order:
            act = project.activities.get(a)
            preds = act.predecessors if act else []
            est_v = max((eft.get(pr, 0) for pr in preds), default=0)
            est[a] = est_v
            dur = act.duration if act else 0
            eft[a] = est_v + dur

        layers = {}
        for node in topo_order:
            layers.setdefault(est[node], []).append(node)

        pos = {}
        for layer_k, nodes_in_layer in layers.items():
            m = len(nodes_in_layer)
            for idx, node in enumerate(nodes_in_layer):
                y_val = (idx - (m - 1) / 2.0) * 1.8
                pos[node] = (float(layer_k), y_val)
    except Exception:
        pos = nx.spring_layout(G, k=0.5, iterations=60, seed=42)

    edge_x, edge_y = [], []
    for edge in G.edges():
        x0, y0 = pos[edge[0]]
        x1, y1 = pos[edge[1]]
        edge_x.extend([x0, x1, None])
        edge_y.extend([y0, y1, None])
        
    edge_trace = go.Scatter(
        x=edge_x, y=edge_y,
        line=dict(width=1.5, color='rgba(148, 163, 184, 0.6)'),
        hoverinfo='none',
        mode='lines'
    )
    
    node_x, node_y, hover_texts, labels = [], [], [], []
    for node in G.nodes():
        x, y = pos[node]
        node_x.append(x)
        node_y.append(y)
        labels.append(str(node))
        act = project.activities.get(node)
        dur = act.duration if act else 0
        res_req = ", ".join([f"R{k}:{v}" for k, v in act.resource_requirements.items() if v > 0]) if act else "None"
        if not res_req:
            res_req = "None (Dummy)"
        hover_texts.append(
            f"<b>Activity {node}</b><br>"
            f"Duration: {dur} days<br>"
            f"Resource Demands: {res_req}<br>"
            f"EST Layer: {pos[node][0]:.1f}"
        )
        
    node_trace = go.Scatter(
        x=node_x, y=node_y,
        mode='markers+text',
        text=labels,
        textposition="middle center",
        hovertext=hover_texts,
        hoverinfo='text',
        marker=dict(
            size=30,
            color='#3b82f6',
            line=dict(width=2, color='#ffffff')
        ),
        textfont=dict(color='white', size=10, family='Arial Black')
    )
    
    fig = go.Figure(data=[edge_trace, node_trace])
    fig.update_layout(
        showlegend=False,
        xaxis=dict(showgrid=True, gridcolor="rgba(200, 200, 200, 0.2)", title="Topological Earliest Start (EST) Timeline", zeroline=False), 
        yaxis=dict(showgrid=False, zeroline=False, showticklabels=False),
        margin=dict(l=20, r=20, t=20, b=30),
        height=520,
        plot_bgcolor="rgba(240, 244, 248, 0.4)"
    )
    return fig

